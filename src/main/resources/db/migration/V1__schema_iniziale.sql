create table catalogo_misure (
    id bigint generated by default as identity primary key,
    codice varchar(10) not null unique,
    nome varchar(255) not null,
    descrizione varchar(255) not null,
    attiva boolean not null default true
);

create table catalogo_comuni (
    codice varchar(50) primary key,
    nome varchar(255) not null
);

create table catalogo_adiacenze (
    id bigint generated by default as identity primary key,
    comune_a varchar(50) not null references catalogo_comuni (codice),
    comune_b varchar(50) not null references catalogo_comuni (codice),
    unique (comune_a, comune_b),
    check (comune_a < comune_b)
);

create table utenze_account (
    id uuid primary key,
    email varchar(254) not null unique,
    password_hash varchar(255) not null,
    nome varchar(255) not null,
    ruolo varchar(20) not null check (ruolo in ('BANCO', 'OPT', 'OPERATORE')),
    stato varchar(30) not null check (stato in ('IN_ATTESA_DI_ATTIVAZIONE', 'ATTIVO', 'REVOCATO'))
);

create table utenze_profili_opt (
    account_id uuid primary key references utenze_account (id),
    codice_struttura varchar(30) not null unique,
    comune_codice varchar(50) not null references catalogo_comuni (codice)
);

create table utenze_profili_operatore (
    account_id uuid primary key references utenze_account (id),
    tipologia varchar(30) not null check (tipologia in ('INTERNO_BANCO', 'ESTERNO_PAGATO_BANCO')),
    comune_codice varchar(50) not null references catalogo_comuni (codice)
);

create table richieste (
    id uuid primary key,
    titolare_id uuid not null references utenze_profili_opt (account_id),
    misura_id bigint not null references catalogo_misure (id),
    comune_codice varchar(50) not null references catalogo_comuni (codice),
    tipo_destinatario varchar(10) not null check (tipo_destinatario in ('PERSONA', 'NUCLEO')),
    description text,
    inviata_il timestamp with time zone not null,
    stato varchar(20) not null check (stato in ('IN_PROGRAMMAZIONE', 'CONFERMATA', 'RIFIUTATA', 'ANNULLATA'))
);
