alter table richieste_contatti_disponibilita
    add column ordine_invio bigint generated by default as identity;

-- Preserva l'ordine logico dello storico già presente, senza affidarsi all'ordine fisico delle righe.
update richieste_contatti_disponibilita c
    set ordine_invio = (
        select o.ordine from (
            select id, row_number() over (order by inviato_il, id) as ordine
            from richieste_contatti_disponibilita
        ) o where o.id = c.id
    );

create unique index contatti_ordine_invio_idx on richieste_contatti_disponibilita (richiesta_id, ordine_invio);
